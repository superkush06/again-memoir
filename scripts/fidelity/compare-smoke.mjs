import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const base = process.argv[2] ?? "http://127.0.0.1:5181/";
const output = resolve(process.argv[3] ?? ".local/depth-fidelity-v1/compare-ui-smoke");
const { chromium } = await import(pathToFileURL("C:/Users/prran/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs").href);
const inventory = await (await fetch(new URL("/api/data", base))).json();
assert.equal(inventory.total, 33);
assert.equal(inventory.measuredCount, 3);
const denied = await fetch(new URL("/api/data", base), { method: "POST" });
assert.equal(denied.status, 405);
const arbitrary = await fetch(new URL("/asset/nonexistent", base));
assert.equal(arbitrary.status, 404);
const browser = await chromium.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true, args: ["--disable-gpu"] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(base, { waitUntil: "load" });
  await page.waitForFunction(() => window.savedComparisonReady === true);
  assert.equal(await page.locator(".photo-card").count(), 33);
  assert.equal(await page.locator("#measured-count").innerText(), "3 / 33 photos measured");
  await page.waitForFunction(() => [...document.querySelectorAll("#comparison-stage img")].length === 2 && [...document.querySelectorAll("#comparison-stage img")].every((img) => img.complete && img.naturalWidth === 960));
  assert.equal(await page.locator("#scores-content tbody tr").count(), 4);
  await page.locator('[data-photo="2"]').click();
  await page.locator("#crop-select").selectOption("phone-hand-contact");
  assert.match(await page.locator("#score-scope").innerText(), /phone-hand-contact/);
  await page.locator('[data-view="right-8cm"]').click();
  await page.locator('[data-mode="swipe"]').click();
  assert.equal(await page.locator("#scores-content table").count(), 0);
  assert.match(await page.locator("#scores-content").innerText(), /No quantitative novel-view result/);
  await page.locator("#swipe-range").evaluate((node) => { node.value = "35"; node.dispatchEvent(new Event("input", { bubbles: true })); });
  assert.equal(await page.locator("#swipe-percent").innerText(), "35%");
  const restoredUrl = page.url();
  assert.match(restoredUrl, /photo=2/);
  assert.match(restoredUrl, /view=right-8cm/);
  assert.match(restoredUrl, /mode=swipe/);
  assert.match(restoredUrl, /crop=phone-hand-contact/);
  await page.reload({ waitUntil: "load" });
  await page.waitForFunction(() => window.savedComparisonReady === true);
  assert.equal(await page.locator("#crop-select").inputValue(), "phone-hand-contact");
  assert.equal(await page.locator('[data-view="right-8cm"]').getAttribute("aria-pressed"), "true");
  assert.equal(await page.locator('[data-mode="swipe"]').getAttribute("aria-pressed"), "true");
  await page.locator("#source-reset").click();
  assert.equal(await page.locator("#crop-select").inputValue(), "full");
  assert.equal(await page.locator('[data-view="source-camera"]').getAttribute("aria-pressed"), "true");
  await page.locator("#right-select").selectOption("plane");
  assert.match(await page.locator("#scores-content").innerText(), /38\.99 dB/);
  await page.locator('[data-photo="4"]').click();
  assert.equal(await page.locator("#comparison-stage .missing").count(), 2);
  assert.equal(await page.locator("#scores-content table").count(), 0);
  assert.match(await page.locator("#availability").innerText(), /not measured/);
  await page.goto(new URL("?photo=1&left=depth-256&right=depth-384&view=source-camera&mode=side&crop=full", base).href, { waitUntil: "load" });
  await page.waitForFunction(() => window.savedComparisonReady === true && [...document.querySelectorAll("#comparison-stage img")].every((img) => img.complete && img.naturalWidth === 960));
  await mkdir(output, { recursive: true });
  await page.screenshot({ path: resolve(output, "desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  const overflow = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth }));
  assert.ok(overflow.scrollWidth <= overflow.width + 1, `Mobile horizontal overflow: ${JSON.stringify(overflow)}`);
  await page.screenshot({ path: resolve(output, "mobile.png"), fullPage: true });
  assert.deepEqual(errors, []);
  const evidence = { passed: true, totalPhotos: 33, measuredPhotos: 3, checks: ["read-only HTTP and unknown asset", "33 existing thumbnail cards", "two complete960px source renders", "source metrics", "fixed ROI selection", "synchronized virtual side view", "side metrics suppressed", "swipe divider", "URL reload restoration", "source reset", "plane-control scores", "unmeasured photo placeholders", "mobile width", "no JavaScript errors"], restoredUrl, screenshots: [resolve(output, "desktop.png"), resolve(output, "mobile.png")], overflow };
  await writeFile(resolve(output, "report.json"), `${JSON.stringify(evidence, null, 2)}\n`);
  process.stdout.write(`${JSON.stringify(evidence, null, 2)}\n`);
} finally { await browser.close(); }
